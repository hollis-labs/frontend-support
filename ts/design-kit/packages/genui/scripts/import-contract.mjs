import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import Ajv2020 from 'ajv/dist/2020.js'
import standalone from 'ajv/dist/standalone/index.js'

const source = process.argv[2]
const revision = process.argv[3]
if (!source || !/^[0-9a-f]{40}$/.test(revision ?? '')) throw new Error('Usage: node scripts/import-contract.mjs <canonical genui directory> <source commit>')
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'contract')
await mkdir(target, { recursive: true })
for (const folder of ['schema', 'fixtures']) await rm(path.join(target, folder), { recursive: true, force: true })
const repository = execFileSync('git', ['-C', source, 'rev-parse', '--show-toplevel'], { encoding: 'utf8' }).trim()
const prefix = path.relative(repository, path.resolve(source)).split(path.sep).join('/')
for (const [from, to] of [['schema', 'schema'], ['testdata/fixtures', 'fixtures']]) {
  const paths = execFileSync('git', ['-C', repository, 'ls-tree', '-r', '--name-only', revision, '--', `${prefix}/${from}`], { encoding: 'utf8' }).trim().split('\n').filter(Boolean)
  if (!paths.length) throw new Error('Canonical source bundle is absent at the requested commit')
  for (const file of paths) {
    const name = file.slice(`${prefix}/${from}/`.length)
    if (name.includes('/')) throw new Error('Unexpected nested canonical bundle file')
    await mkdir(path.join(target, to), { recursive: true })
    await writeFile(path.join(target, to, name), execFileSync('git', ['-C', repository, 'show', `${revision}:${file}`]))
  }
}
await writeFile(path.join(target, 'LICENSE'), execFileSync('git', ['-C', repository, 'show', `${revision}:LICENSE`]))
const schema = JSON.parse(await readFile(path.join(target, 'schema/contract.schema.json'), 'utf8'))
const literal = value => JSON.stringify(value)
function type(s) {
  if (s.$ref) return s.$ref.split('/').at(-1)
  if ('const' in s) return literal(s.const)
  if (s.enum) return s.enum.map(literal).join(' | ')
  if (s.oneOf || s.anyOf) return (s.oneOf ?? s.anyOf).map(v => `(${type(v)})`).join(' | ')
  if (s.type === 'array') return `Array<${type(s.items)}>`
  if (s.type === 'object') {
    const fields = Object.entries(s.properties ?? {}).map(([key, value]) => `${literal(key)}${s.required?.includes(key) ? '' : '?'}: ${type(value)}`)
    if (s.additionalProperties && typeof s.additionalProperties === 'object') fields.push(`[key: string]: ${type(s.additionalProperties)}`)
    return `{ ${fields.join('; ')} }`
  }
  if (s.type === 'integer' || s.type === 'number') return 'number'
  if (['string', 'boolean', 'null'].includes(s.type)) return s.type
  throw new Error('Unsupported schema shape for type generation')
}
await mkdir(path.join(root, 'src'), { recursive: true })
await writeFile(path.join(root, 'src/generated.ts'), '// Generated mechanically from contract/schema/contract.schema.json. Do not edit.\n' + Object.entries(schema.$defs).map(([name, value]) => `export type ${name} = ${type(value)}\n`).join(''))
const ajv = new Ajv2020({ strict: false, allErrors: false, validateFormats: false, code: { source: true, esm: true, lines: true } })
ajv.addSchema(schema)
const entries = Object.fromEntries(Object.keys(schema.$defs).map(name => [name, `${schema.$id}#/$defs/${name}`]))
let validators = standalone(ajv, entries)
// AJV's standalone generator emits CJS helper references even with ESM exports.
// Convert only its known static helper imports; refuse any unexpected require.
validators = validators.replace(/const (\w+) = require\("(ajv\/dist\/runtime\/[^"\n]+)"\)\.default;/g, (_, binding, module) => `import * as ${binding}Module from "${module}.js";\nconst ${binding} = typeof ${binding}Module.default === "function" ? ${binding}Module.default : ${binding}Module.default.default;`)
if (validators.includes('require(')) throw new Error('Unsupported standalone validator dependency')
await writeFile(path.join(root, 'src/validators.js'), '// Generated by AJV standalone from the canonical schema. Do not edit.\n' + validators)
await writeFile(path.join(root, 'src/validators.d.ts'), '// Generated from the canonical schema. Do not edit.\n' + Object.keys(entries).map(name => `export declare function ${name}(value: unknown): boolean\n`).join(''))
const hashes = [{ path: 'LICENSE', sha256: createHash('sha256').update(await readFile(path.join(target, 'LICENSE'))).digest('hex') }]
for (const folder of ['schema', 'fixtures']) {
  for (const name of (await readdir(path.join(target, folder))).sort()) {
    const file = `${folder}/${name}`
    hashes.push({ path: file, sha256: createHash('sha256').update(await readFile(path.join(target, file))).digest('hex') })
  }
}
await writeFile(path.join(target, 'provenance.json'), JSON.stringify({ source: `https://github.com/hollis-labs/substrate/tree/${revision}/genui`, revision, contract_version: '1', files: hashes }, null, 2) + '\n')
